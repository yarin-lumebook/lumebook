"""Coverage log: one row per selected Reel with what evidence exists and what has been done.
Writes coverage.md (human) and coverage.json (machine). Safe to rerun at any time; it only reads files."""
import json, os
M = '/Users/yarinbruner/Claude/Projects/Lumebook/media/projects/2026-11-09-matan-nistor-reels'
order = [l.strip() for l in open('all120_codes.txt') if l.strip()]
metrics = json.load(open('metrics.json'))
verified = json.load(open('verified.json')) if os.path.exists('verified.json') else {}
checked = {}
if os.path.exists('transcript_check_log.jsonl'):
    for l in open('transcript_check_log.jsonl'):
        if l.strip():
            o = json.loads(l)
            checked[o['code']] = o.get('transcript', '')
rows = []
for c in order:
    a = f'{M}/analysis/{c}'
    idx = json.load(open(f'{a}/index.json')) if os.path.exists(f'{a}/index.json') else None
    w = f'{a}/whisper.txt'
    tr = 'none'
    if os.path.exists(w):
        txt = open(w).read().strip()
        tr = 'speech' if len(txt) > 20 else 'empty_or_music'
    coded = os.path.exists(f'coded/{c}.json')
    ev = {}
    if coded:
        try:
            ev = json.load(open(f'coded/{c}.json')).get('evidence', {})
        except Exception:
            ev = {'error': 'invalid json'}
    m = metrics[c]
    rows.append({'code': c, 'group': m['group'], 'rank': m['rank_top100'], 'video': os.path.exists(f'{M}/videos/{c}.mp4'),
                 'cover': os.path.exists(f'{M}/covers/{c}.jpg'), 'frames': bool(idx), 'sheets': len(idx['sheets']) if idx else 0,
                 'transcript': tr, 'comments_sampled': os.path.exists(f'dossiers/{c}.json'), 'coded': coded,
                 'coder_transcript': ev.get('transcript'), 'coder_sheets_opened': ev.get('sheets_opened'),
                 'speech_checked': checked.get(c, ''), 'verified_by_me': verified.get(c, '')})
json.dump(rows, open('coverage.json', 'w'), indent=1)
n = lambda k: sum(1 for r in rows if r[k])
lines = ['# Coverage log', '', 'Regenerated by `src/coverage.py`. One row per selected Reel (100 top + 20 comparisons).', '',
         f"Videos {n('video')}/120, frames {n('frames')}/120, transcripts {sum(r['transcript']!='none' for r in rows)}/120, coded {n('coded')}/120, speech fields checked against the transcript {n('speech_checked')}/120, checked by me {sum(bool(r['verified_by_me']) for r in rows)}/120.", '',
         '| # | Reel | Group | Rank | Video | Frames | Transcript | Coded | Coder saw sheets | Coder transcript | Speech check | Checked by me |', '|---|---|---|---|---|---|---|---|---|---|---|---|']
for i, r in enumerate(rows, 1):
    lines.append(f"| {i} | {r['code']} | {r['group']} | {r['rank'] or ''} | {'y' if r['video'] else 'n'} | {r['sheets'] or 'n'} | {r['transcript']} | {'y' if r['coded'] else 'n'} | {r['coder_sheets_opened'] or ''} | {r['coder_transcript'] or ''} | {r['speech_checked']} | {r['verified_by_me']} |")
open('../coverage.md', 'w').write('\n'.join(lines) + '\n')
print(lines[4])
