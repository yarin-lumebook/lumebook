"""Side-by-side table of the 20 top/comparison pairs from the coded files: match quality computed from the coded
topic, format and duration (not from the coders' opinion, since several coders could not open the paired Reel),
plus the opening and structure features that differ. Writes pairs.md and pairs.json."""
import json, os
metrics = json.load(open('metrics.json'))
pairs = json.load(open('comparisons.json'))['pairs']
def ld(c):
    p = f'coded/{c}.json'
    return json.load(open(p)) if os.path.exists(p) else None
def first(s): return (str(s or '').split(' ')[0].split(':')[0]).strip(' ,.(').lower()
def lst(x): return [first(i) for i in (x or [])] if isinstance(x, list) else [first(x)]
out = []
import csv
XM = {r['code']: r['views_vs_month_median'] for r in csv.DictReader(open('../data/reels.csv', encoding='utf-8-sig'))}
L = ['# Matched pairs (generated by pairs_table.py)', '', 'Match: topic and format from the coded files of both Reels; duration within 30% of the top Reel. Views and "x month" (views divided by the median of all his Reels that month) read 09 Nov 2026.', '',
     '| Top (rank) | Comparison | Views top / cmp | x month top / cmp | Topic | Format | Duration | Standalone first line top / cmp | Number in 3 s top / cmp | B-roll top / cmp | Structure top / cmp |', '|---|---|---|---|---|---|---|---|---|---|---|']
for p in pairs:
    t, c = ld(p['top']), ld(p['cmp'])
    mt, mc = metrics[p['top']], metrics[p['cmp']]
    if not t or not c:
        L.append(f"| {p['top']} | {p['cmp']} | not coded yet |"); continue
    topic = 'same' if first(t.get('topic')) == first(c.get('topic')) else 'different'
    fmt = 'same' if first(t.get('format')) == first(c.get('format')) else 'different'
    dur = 'within 30%' if abs(mt['duration_s'] - mc['duration_s']) <= 0.3 * mt['duration_s'] else 'not'
    row = {'top': p['top'], 'cmp': p['cmp'], 'topic': topic, 'format': fmt, 'duration': dur,
           'top_topic': first(t.get('topic')), 'cmp_topic': first(c.get('topic')), 'top_format': first(t.get('format')), 'cmp_format': first(c.get('format')),
           'standalone': (first(t['opening'].get('first_sentence_standalone')), first(c['opening'].get('first_sentence_standalone'))),
           'number3s': (first(t['opening'].get('number_or_money_in_first_3s')), first(c['opening'].get('number_or_money_in_first_3s'))),
           'broll': (lst(t['visual'].get('broll_source')), lst(c['visual'].get('broll_source'))),
           'structure': (first(t['story'].get('structure')), first(c['story'].get('structure')))}
    out.append(row)
    L.append(f"| {p['top']} ({mt['rank_top100']}) | {p['cmp']} | {mt['views_grid']:,} / {mc['views_grid']:,} | {XM[p['top']]} / {XM[p['cmp']]} | {topic} ({row['top_topic']} / {row['cmp_topic']}) | {fmt} ({row['top_format']} / {row['cmp_format']}) | {dur} ({mt['duration_s']} / {mc['duration_s']} s) | {row['standalone'][0]} / {row['standalone'][1]} | {row['number3s'][0]} / {row['number3s'][1]} | {', '.join(row['broll'][0])} / {', '.join(row['broll'][1])} | {row['structure'][0]} / {row['structure'][1]} |")
good = [r for r in out if r['topic'] == 'same' and r['format'] == 'same' and r['duration'] == 'within 30%']
L += ['', f"Pairs coded on both sides: {len(out)}/20. Same topic: {sum(r['topic']=='same' for r in out)}. Same format: {sum(r['format']=='same' for r in out)}. Duration within 30%: {sum(r['duration']=='within 30%' for r in out)}. All three: {len(good)} ({', '.join(r['top']+'/'+r['cmp'] for r in good)})."]
open('pairs.md', 'w').write('\n'.join(L) + '\n')
json.dump(out, open('pairs.json', 'w'), ensure_ascii=False, indent=1)
print(L[-1])
